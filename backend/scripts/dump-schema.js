// Writes backend/database/schema.sql: a readable snapshot of the real database schema
// (DB_SCHEMA) - every enum type, table, column, constraint and index. Read-only: it only
// queries the Postgres catalog, never data, never changes anything.
//
//   npm run db:sync      # create/upgrade the schema (models + src/database/migrations)
//   npm run db:schema    # then refresh the snapshot, and commit it with the change
//   npm run db:schema -- --out /tmp/schema.sql   # write somewhere else (e.g. to compare)
//
// The snapshot is documentation for people (one place to see the whole database, and a
// readable git diff when it changes). It is NOT used to create the database.
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const { QueryTypes } = require('sequelize');
const { sequelize, schema } = require('../src/database/config');

const outArg = process.argv.indexOf('--out');
const OUT = outArg !== -1 ? path.resolve(process.argv[outArg + 1]) : path.join(__dirname, '..', 'database', 'schema.sql');
const q = (sql) => sequelize.query(sql, { replacements: { schema }, type: QueryTypes.SELECT });

async function main() {
  const [enums, columns, constraints, indexes, migrations] = await Promise.all([
    q(`SELECT t.typname AS name, array_agg(e.enumlabel ORDER BY e.enumsortorder) AS labels
       FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid JOIN pg_namespace n ON n.oid = t.typnamespace
       WHERE n.nspname = :schema GROUP BY t.typname ORDER BY t.typname`),
    q(`SELECT c.relname AS "table", a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type,
              a.attnotnull AS "notNull", pg_get_expr(d.adbin, d.adrelid) AS "default"
       FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
       JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
       LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
       WHERE n.nspname = :schema AND c.relkind = 'r'
       ORDER BY c.relname, a.attnum`),
    q(`SELECT c.relname AS "table", con.conname AS name, con.contype AS kind, pg_get_constraintdef(con.oid) AS def
       FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE n.nspname = :schema AND c.relkind = 'r'
       ORDER BY c.relname, CASE con.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'f' THEN 2 ELSE 3 END, con.conname`),
    // Indexes that aren't the implementation of a primary key / unique constraint
    q(`SELECT i.tablename AS "table", i.indexname AS name, i.indexdef AS def
       FROM pg_indexes i
       WHERE i.schemaname = :schema
         AND NOT EXISTS (SELECT 1 FROM pg_constraint con JOIN pg_class ic ON ic.oid = con.conindid
                         JOIN pg_namespace n ON n.oid = ic.relnamespace
                         WHERE n.nspname = :schema AND ic.relname = i.indexname)
       ORDER BY i.tablename, i.indexname`),
    q(`SELECT to_regclass(:schema || '.schema_migrations') IS NOT NULL AS present`)
      .then(async ([r]) => (r.present ? q(`SELECT name FROM "${schema}".schema_migrations ORDER BY name`) : []))
  ]);

  // Drop the schema prefix so the file reads the same whatever DB_SCHEMA is
  const strip = (text) => text.split(`"${schema}".`).join('').split(`${schema}.`).join('');

  const tables = [...new Set(columns.map(c => c.table))];
  const out = [];
  out.push('-- SmartWorkforce AI - database schema snapshot');
  out.push('--');
  out.push('-- GENERATED by `npm run db:schema` from the real database. Do not edit by hand and do not');
  out.push('-- run this file: the schema is created by the Sequelize models + src/database/migrations');
  out.push('-- via `npm run db:sync`. Regenerate and commit it whenever a migration or model changes.');
  out.push('--');
  out.push(`-- Tables: ${tables.length}. Applied migrations: ${migrations.length ? migrations.map(m => m.name).join(', ') : 'none'}`);
  out.push('-- All objects live in the DB_SCHEMA schema (e.g. smartai); the prefix is omitted below.');
  out.push('');

  if (enums.length) {
    out.push('-- ===== Enum types =====', '');
    enums.forEach(e => {
      const labels = Array.isArray(e.labels) ? e.labels : String(e.labels).replace(/^{|}$/g, '').split(',');
      out.push(`CREATE TYPE ${e.name} AS ENUM (${labels.map(l => `'${String(l).replace(/^"|"$/g, '')}'`).join(', ')});`);
    });
    out.push('');
  }

  out.push('-- ===== Tables =====');
  tables.forEach(table => {
    const cols = columns.filter(c => c.table === table).map(c => {
      let line = `  ${c.name} ${strip(c.type)}`;
      if (c.notNull) line += ' NOT NULL';
      if (c.default !== null) line += ` DEFAULT ${strip(c.default)}`;
      return line;
    });
    const cons = constraints.filter(c => c.table === table).map(c => `  CONSTRAINT ${c.name} ${strip(c.def)}`);
    out.push('', `CREATE TABLE ${table} (`, [...cols, ...cons].join(',\n'), ');');
    indexes.filter(i => i.table === table).forEach(i => out.push(`${strip(i.def)};`));
  });
  out.push('');

  fs.writeFileSync(OUT, out.join('\n'));
  console.info(`[db:schema] Wrote ${path.relative(process.cwd(), OUT)} - ${tables.length} tables, ${enums.length} enum types, ${indexes.length} indexes (schema "${schema}")`);
}

main()
  .then(() => sequelize.close())
  .catch(async (error) => {
    console.error('[db:schema] Failed:', error.message);
    await sequelize.close().catch(() => {});
    process.exit(1);
  });
