const express = require('express');
const router = express.Router();
const analyticsController = require('../../controllers/analyticsController');
const { authenticate, authorize } = require('../../middleware/auth');
const { IS_MANAGER_UP, IS_HR_UP, ROLES } = require('../../config/constants');
const { validate, validateQuery, validateUUID, schemas } = require('../../middleware/validation');

// ---- Dashboard ----
router.get('/dashboard', authenticate, analyticsController.getDashboard);
router.get('/live/dashboard', authenticate, analyticsController.getDashboard);   // polled variant, same data
router.get('/live/online-users', authenticate, analyticsController.getOnlineUsers);

// ---- AI insights ----
router.get('/ai-insights/me', authenticate, analyticsController.getMyInsights);
router.get('/ai-insights/team', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getTeamInsights);
router.get('/ai-insights/organization', authenticate, authorize(...IS_HR_UP), analyticsController.getOrganizationInsights);
router.get('/ai-insights/history', authenticate, analyticsController.getInsightHistory);

// ---- Attendance ----
router.get('/attendance/trends', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getAttendanceTrends);
router.get('/attendance/departments', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getDepartmentAttendance);
router.get('/attendance/late-patterns', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getLatePatterns);
router.get('/attendance/user/:userId', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getUserAttendance);

// ---- Leave ----
router.get('/leave/statistics', authenticate, authorize(...IS_HR_UP), analyticsController.getLeaveStatistics);
router.get('/leave/types-distribution', authenticate, authorize(...IS_HR_UP), analyticsController.getLeaveTypeDistribution);
router.get('/leave/departments', authenticate, authorize(...IS_HR_UP), analyticsController.getDepartmentLeave);

// ---- Performance (attendance-derived proxy) ----
router.get('/performance/overview', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getPerformanceOverview);
router.get('/performance/team/:teamId', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getTeamPerformance);
router.get('/performance/user/:userId', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getUserPerformance);

// ---- Anomalies ----
router.get('/anomalies', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getAnomalies);
router.get('/anomalies/organization', authenticate, authorize(...IS_HR_UP), analyticsController.getOrganizationAnomalies);

// ---- Team / department comparison ----
router.get('/team/:teamId/overview', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getTeamOverview);
router.get('/manager/dashboard', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getManagerDashboard);
router.get('/departments/comparison', authenticate, authorize(...IS_MANAGER_UP), analyticsController.getDepartmentComparison);

// ---- Workforce metrics (SQL aggregation, role-scoped: org / own team / self) ----
router.get('/me/summary', authenticate, validateQuery(schemas.periodQuery), analyticsController.getMySummary);
router.get('/work-mode', authenticate, validateQuery(schemas.periodQuery), analyticsController.getWorkMode);
router.get('/overtime', authenticate, validateQuery(schemas.periodQuery), analyticsController.getOvertime);
router.get('/approvals/turnaround', authenticate, authorize(...IS_MANAGER_UP), validateQuery(schemas.periodQuery), analyticsController.getApprovalTurnaround);
router.get('/lifecycle', authenticate, authorize(...IS_HR_UP), validateQuery(schemas.lifecycleQuery), analyticsController.getLifecycle);
router.get('/leave/utilization', authenticate, authorize(...IS_HR_UP), validateQuery(schemas.yearQuery), analyticsController.getLeaveUtilization);

// ---- KPI engine (precomputed daily KPIs, long ranges) ----
router.get('/kpis', authenticate, authorize(...IS_HR_UP), validateQuery(schemas.kpiQuery), analyticsController.getKpis);

// ---- Risk scores (2E) - managers: their team; HR/Admin: organization ----
router.get('/risk', authenticate, authorize(...IS_MANAGER_UP), validateQuery(schemas.riskQuery), analyticsController.getRiskOverview);
router.get('/risk/:userId', authenticate, authorize(...IS_MANAGER_UP), validateUUID('userId'), analyticsController.getEmployeeRisk);

// ---- Forecasting (2E) ----
router.get('/forecast/leave', authenticate, authorize(...IS_MANAGER_UP), validateQuery(schemas.leaveForecastQuery), analyticsController.getLeaveForecast);
router.get('/forecast/attendance', authenticate, authorize(...IS_MANAGER_UP), validateQuery(schemas.forecastQuery), analyticsController.getAttendanceForecast);

// ---- Persisted reports (generated by the report worker) ----
router.post('/reports', authenticate, authorize(...IS_MANAGER_UP), validate(schemas.createReport), analyticsController.requestReport);
router.get('/reports', authenticate, authorize(...IS_MANAGER_UP), analyticsController.listReports);
router.get('/reports/:id', authenticate, authorize(...IS_MANAGER_UP), validateUUID('id'), analyticsController.getReport);
router.get('/reports/:id/download', authenticate, authorize(...IS_MANAGER_UP), validateUUID('id'), analyticsController.downloadReport);

// ---- System (Admin) ----
router.get('/system/health', authenticate, authorize(ROLES.ADMIN), analyticsController.getSystemHealth);
router.get('/system/api-usage', authenticate, authorize(ROLES.ADMIN), analyticsController.getApiUsage);

// ---- Export ----
router.post('/export', authenticate, analyticsController.export);
router.get('/export/:id', authenticate, authorize(...IS_MANAGER_UP), validateUUID('id'), analyticsController.downloadReport);

module.exports = router;
