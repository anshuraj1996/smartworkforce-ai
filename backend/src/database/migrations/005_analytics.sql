-- Analytics (Phase 2D): the KPI store, its refresh queue, and persisted workforce reports.
-- All three are owned by migrations (raw-SQL repositories), not Sequelize models.

-- 1) Daily KPI snapshot per organization, day and department.
--    Written only by the KPI worker (KpiRepository.recomputeDay), which recomputes a whole
--    org-day from the source tables - so a row is always "the truth as of computed_at", never a
--    running counter that a duplicate or lost event could skew. Long-range dashboards
--    (months/years, HR + executive) read these few rows instead of scanning attendance_logs.
CREATE TABLE IF NOT EXISTS daily_kpis (
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  kpi_date date NOT NULL,
  department text NOT NULL,                       -- 'Unassigned' when an employee has none
  is_working_day boolean NOT NULL,                -- from the org's default shift
  headcount integer NOT NULL DEFAULT 0,           -- active employees (hired by that day)
  present integer NOT NULL DEFAULT 0,             -- any attendance except ABSENT
  late integer NOT NULL DEFAULT 0,
  wfh integer NOT NULL DEFAULT 0,
  half_day integer NOT NULL DEFAULT 0,
  on_leave integer NOT NULL DEFAULT 0,            -- approved leave covering the day
  absent integer NOT NULL DEFAULT 0,              -- working days: headcount - present - on_leave
  working_minutes bigint NOT NULL DEFAULT 0,
  worked_days integer NOT NULL DEFAULT 0,         -- logs with working minutes (for averages)
  overtime_minutes bigint NOT NULL DEFAULT 0,     -- minutes beyond the standard day
  late_minutes bigint NOT NULL DEFAULT 0,
  leave_requested integer NOT NULL DEFAULT 0,     -- requests created that day
  wfh_requested integer NOT NULL DEFAULT 0,
  requests_decided integer NOT NULL DEFAULT 0,    -- leave + WFH + regularization decided that day
  decision_minutes bigint NOT NULL DEFAULT 0,     -- sum of request -> decision time of those
  computed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (organization_id, kpi_date, department)
);

-- 2) Which org-days need recomputing. Event handlers only upsert a row here (cheap and
--    idempotent - a redelivered event just upserts again); the refresh worker claims rows with
--    SKIP LOCKED, recomputes, and deletes them. Durable: a worker crash loses nothing, and a
--    burst of 200 check-ins becomes one recompute instead of 200.
CREATE TABLE IF NOT EXISTS kpi_refresh_queue (
  organization_id uuid NOT NULL,
  kpi_date date NOT NULL,
  requested_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (organization_id, kpi_date)
);

-- 3) Persisted workforce reports, generated asynchronously by the report worker.
CREATE TABLE IF NOT EXISTS workforce_reports (
  id uuid PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  report_type text NOT NULL,
  period_start date NOT NULL,
  period_end date NOT NULL,
  -- NULL = whole organization; a manager's reports cover only their direct reports
  scope_manager_id uuid REFERENCES users(id) ON DELETE CASCADE,
  -- NULL = generated by the monthly schedule
  requested_by uuid REFERENCES users(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'READY', 'FAILED')),
  summary jsonb,
  row_count integer,
  content text,                                   -- the CSV
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CHECK (period_start <= period_end)
);

-- Report list, newest first
CREATE INDEX IF NOT EXISTS idx_workforce_reports_org_created
  ON workforce_reports (organization_id, created_at DESC);

-- A scheduled report exists once per org/type/period, so a re-run of the monthly job (restart,
-- second replica) can't create a duplicate
CREATE UNIQUE INDEX IF NOT EXISTS uq_workforce_reports_scheduled
  ON workforce_reports (organization_id, report_type, period_start, period_end)
  WHERE requested_by IS NULL AND scope_manager_id IS NULL;
